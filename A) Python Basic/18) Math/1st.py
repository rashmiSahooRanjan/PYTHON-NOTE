# Min() :-
a= min(1,2,3,4,5)
print(a)

# Max() :-
b= max(1,2,3,4,5)
print(b)

# abs() :- it remove the negative sign and give the positive value
c= abs(-5)
print(c)

# pow(x, y) :- it is used to calculate the power of a number
d= pow(2,3) 
print(d)

# Math module :- import math
import math
# math.sqrt() :- it is used to calculate the square root of a number
e= math.sqrt(16)
print(e)

# math.ceil() :- it is used to round up the number to the nearest integer
f= math.ceil(4.2)
print(f)

# math.floor() :- it is used to round down the number to the nearest integer
g= math.floor(4.8)
print(g)

# math.pi :- it is used to get the value of pi
h= math.pi
print(h)