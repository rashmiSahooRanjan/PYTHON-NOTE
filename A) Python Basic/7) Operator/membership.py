#1. in (it check the value present in list or not. if present then answer come true otherwise false.)
fruits = ["apple", "banana", "cherry"]
print("banana" in fruits)
print("grape" in fruits)

#2. not in (it check the value not present in list or not. if not present then answer come true otherwise false.)
fruits = ["apple", "banana", "cherry"]  
print("grape" not in fruits)
print("banana" not in fruits)