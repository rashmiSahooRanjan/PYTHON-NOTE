a=10;
b=15;

#Equal(==)
print("Equal(==)",a==b);

#Not Equal(!=)
print("Not Equal(!=)",a!=b);

#Greater than(>)
print("Greater than(>)",a>b);

#Less than(<)
print("Less than(<)",a<b);

#Greater than or Equal to(>=)
print("Greater than or Equal to(>=)",a>=b);

#Less than or Equal to(<=)
print("Less than or Equal to(<=)",a<=b);